import json
import os
import re
import subprocess
import sys
from pathlib import Path

from devflow.registry import change_directories
from devflow.tasks import parse_tasks


ROOT = Path(__file__).resolve().parent.parent
HISTORICAL = {
    "bootstrap-devflow",
    "restart-solver-core",
    "redesign-development-workflow",
    "upgrade-devflow-0-3-1",
}


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def run_json(command):
    env = dict(os.environ)
    env["PYTHONNOUSERSITE"] = "1"
    result = subprocess.run(
        command,
        cwd=ROOT,
        env=env,
        check=False,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="backslashreplace",
    )
    output = result.stdout + result.stderr
    if result.returncode:
        raise RuntimeError(f"{' '.join(map(str, command))} exited {result.returncode}: {output.strip()}")
    return json.loads(result.stdout)


def embedded(path):
    text = path.read_text(encoding="utf-8")
    match = re.search(r'id="roadmap-data">\n(.*?)\n</script>', text, re.S)
    require(match is not None, f"Missing embedded roadmap data in {path}")
    return json.loads(match.group(1))


def check_committed_view():
    output = ROOT / "internal/roadmap.html"
    before = output.read_bytes() if output.exists() else None
    first_report = run_json([sys.executable, "-m", "devflow", "roadmap-view"])
    require(first_report["roadmapView"] == "internal/roadmap.html", "Unexpected ordinary view output path")
    first = output.read_bytes()
    second_report = run_json([sys.executable, "-m", "devflow", "roadmap-view"])
    require(second_report["roadmapView"] == "internal/roadmap.html", "Ordinary view path changed between runs")
    second = output.read_bytes()
    require(first == second, "Ordinary roadmap generation is not deterministic")
    require(before is None or before == first, "Committed roadmap.html is stale or was edited by hand")

    text = first.decode("utf-8")
    require("Generated by devflow roadmap-view" in text, "Official generator marker is missing")
    require("__ROADMAP_" not in text, "Template markers were not fully replaced")
    require(str(ROOT) not in text and "runs/worktrees" not in text, "Ordinary view contains machine-local paths")
    data = embedded(output)
    require(data["live"] is None, "Ordinary view contains a live overlay")
    require(data["formatVersion"] == 2, "Ordinary view has the wrong plan format")
    require(data.get("globalMap") is None and data.get("parallelPlan") is None, "Minimal view unexpectedly contains optional display maps")
    for change in data["changes"]:
        require("tasks" not in change and "merged" not in change, "Ordinary Change entry contains machine state")
    return f"deterministic ordinary view, {len(first)} bytes, {len(data['changes'])} Changes"


def check_live_view():
    report = run_json([sys.executable, "-m", "devflow", "roadmap-view", "--live"])
    require(report["roadmapView"] == "runs/views/roadmap.html", "Unexpected live view output path")
    output = ROOT / "runs/views/roadmap.html"
    data = embedded(output)
    live = data["live"]
    require(live is not None, "Live view has no local overlay")
    require(live["integrationBranch"] == "main", "Unexpected integration branch")
    require(isinstance(live["locks"], list), "Live locks must be a list")
    require(HISTORICAL <= set(live["merged"]), "Historical archived Changes must be merged on main")
    worktrees = {Path(entry["path"]).resolve() for entry in live["worktrees"]}
    require(ROOT.resolve() in worktrees, "Live view does not include the current worktree")

    directories = change_directories(ROOT)
    active = sorted(change for change, path in directories.items() if not path.startswith("archive/"))
    require(live["tasks"].keys() == set(active), "Live task keys do not match active Changes")
    for change_id in active:
        relative = directories[change_id]
        tasks_path = ROOT / "openspec/changes" / relative / "tasks.md"
        if not tasks_path.is_file():
            require(live["tasks"][change_id] == {"complete": 0, "total": 0}, f"Unexpected task count for {change_id}")
            continue
        tasks = parse_tasks(tasks_path.read_text(encoding="utf-8"))
        expected = {"complete": sum(task.done for task in tasks), "total": len(tasks)}
        require(live["tasks"][change_id] == expected, f"Live task count differs from tasks.md for {change_id}")
    require(data["now"]["active"] == active, "Live active Change list is inconsistent")
    return f"live view: worktrees={len(worktrees)}, activeTasks={len(active)}, historicalMerged={len(HISTORICAL)}"


def main():
    checks = [
        ("ordinary roadmap view", check_committed_view),
        ("live roadmap view", check_live_view),
    ]
    failures = []
    for name, check in checks:
        try:
            detail = check()
        except Exception as error:
            failures.append(name)
            print(f"FAIL {name}: {error}")
        else:
            print(f"PASS {name}: {detail}")
    if failures:
        print(f"Roadmap view checks failed: {', '.join(failures)}")
        return 1
    print("Roadmap view checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
